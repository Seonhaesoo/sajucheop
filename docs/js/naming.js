  function recommend(sur, gender, lackEls, count) {
    count = count || 8;
    var genderOk = function (c) { return c.g === 'A' || c.g === gender; };
    var pool = HANJA.filter(genderOk);
    var firstPool = (lackEls && lackEls.length)
      ? pool.filter(function (c) { return lackEls.indexOf(c.e) >= 0; })
      : pool;
    if (!firstPool.length) firstPool = pool;

    var found = [];
    for (var i = 0; i < firstPool.length; i++) {
      for (var k = 0; k < pool.length; k++) {
        var c1 = firstPool[i], c2 = pool[k];
        if (c1.h === c2.h || c1.r === c2.r) continue;
        /* 수리 전 격 길 이상 */
        if (su81(c1.s + c2.s).tier === '흉' || su81(c1.s + c2.s).tier === '평') continue;
        if (su81(sur.s + c1.s).tier === '흉' || su81(sur.s + c1.s).tier === '평') continue;
        if (su81(sur.s + c2.s).tier === '흉' || su81(sur.s + c2.s).tier === '평') continue;
        if (su81(sur.s + c1.s + c2.s).tier === '흉' || su81(sur.s + c1.s + c2.s).tier === '평') continue;
        var ev = evaluate(sur, [c1, c2], lackEls);
        if (ev.sound.clash || !ev.eumyang.mixed) continue;
        if (ev.total < 80) continue;
        found.push({ c1: c1, c2: c2, ev: ev });
      }
    }
    found.sort(function (a, b) { return b.ev.total - a.ev.total; });
    /* 같은 소리 조합 중복 제거 */
    var seen = {}, uniq = [];
    for (var f = 0; f < found.length; f++) {
      var key = found[f].c1.r + found[f].c2.r;
      if (seen[key]) continue;
      seen[key] = 1;
      uniq.push(found[f]);
    }
    /* 상위권에서 무작위로 뽑아 다양성 */
    var top = uniq.slice(0, Math.max(count * 4, 32));
    var picked = [];
    while (picked.length < count && top.length) {
      picked.push(top.splice(Math.floor(Math.random() * top.length), 1)[0]);
    }
    return picked;
  }

