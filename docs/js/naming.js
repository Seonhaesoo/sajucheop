  var TIER_SCORE = { '대길': 12, '길': 9, '평': 5, '흉': 0 };

  /* sur: {r, s}  chars: [{r, s, e(옵션), h(옵션)}] 1~2자  lackEls: ['수', ...] | null */
  function evaluate(sur, chars, lackEls) {
    var one = chars.length === 1;
    var n1 = chars[0], n2 = chars[1] || null;

    /* 수리 4격 (외자는 3격) */
    var gyeok = [];
    gyeok.push({ name: '원격', desc: '초년·바탕', su: su81(one ? n1.s : n1.s + n2.s) });
    gyeok.push({ name: '형격', desc: '청년·주운', su: su81(sur.s + n1.s) });
    if (!one) gyeok.push({ name: '이격', desc: '중년·대외', su: su81(sur.s + n2.s) });
    gyeok.push({ name: '정격', desc: '총운·말년', su: su81(sur.s + n1.s + (n2 ? n2.s : 0)) });

    var suScore = 0;
    gyeok.forEach(function (g) { suScore += TIER_SCORE[g.su.tier]; });
    if (one) suScore = Math.round(suScore * 4 / 3);

    /* 발음오행 */
    var els = [soundElOf(sur.r)].concat(chars.map(function (c) { return soundElOf(c.r); }));
    var rels = [];
    for (var i = 0; i < els.length - 1; i++) rels.push(elRel(els[i], els[i + 1]));
    var minRel = Math.min.apply(null, rels);
    var sumRel = rels.reduce(function (a, b) { return a + b; }, 0);
    var soundScore = minRel === 0 ? 0 : (sumRel >= rels.length * 2 ? 14 : (sumRel > rels.length ? 10 : 6));
    var soundLine = minRel === 0
      ? '초성 오행(' + els.join('·') + ')에 상극이 끼어 소리 흐름이 부딪혀요.'
      : (soundScore >= 14 ? '초성 오행(' + els.join('·') + ')이 서로를 살리는 상생의 소리예요.'
        : (soundScore >= 10 ? '초성 오행(' + els.join('·') + ')이 무난하게 이어지는 소리예요.'
          : '초성 오행(' + els.join('·') + ')이 같은 기운으로 나란한 소리예요.'));

    /* 자원오행 — 사주 보완 */
    var jawonScore = 0, jawonLine = null;
    if (lackEls && lackEls.length) {
      var matched = [];
      chars.forEach(function (c) {
        if (c.e && lackEls.indexOf(c.e) >= 0) { jawonScore += 5; matched.push(c.h + '(' + c.e + ')'); }
      });
      jawonScore = Math.min(10, jawonScore);
      jawonLine = matched.length
        ? matched.join(', ') + ' — 명식에 부족한 ' + lackEls.join('·') + ' 기운을 글자가 채워줘요.'
        : '이 글자들은 명식에 부족한 ' + lackEls.join('·') + ' 기운을 직접 채우진 않아요.';
    }

    /* 음양 (획수 홀짝) */
    var parities = [sur.s % 2].concat(chars.map(function (c) { return c.s % 2; }));
    var allSame = parities.every(function (p) { return p === parities[0]; });
    var eumyangScore = allSame ? 0 : 6;

    /* 불용한자 */
    var warns = [];
    chars.forEach(function (c) {
      if (c.h && isBulyong(c.h)) {
        warns.push(c.h + ' — 전통 작명에서 피하는 글자예요 (뜻이 너무 크거나, 흉하거나, 스러지는 상). 절대 금지는 아니에요.');
      }
    });

    var total = 22 + suScore + soundScore + jawonScore + eumyangScore - warns.length * 15;
    total = Math.max(5, Math.min(100, total));

    var tier = total >= 88 ? '아주 좋은 이름' : (total >= 75 ? '좋은 이름'
      : (total >= 60 ? '무난한 이름' : (total >= 45 ? '아쉬운 이름' : '다시 고려해 볼 이름')));

    return {
      total: total, tier: tier,
      gyeok: gyeok,
      sound: { els: els, score: soundScore, line: soundLine, clash: minRel === 0 },
      jawon: { score: jawonScore, line: jawonLine },
      eumyang: { mixed: !allSame, line: allSame ? '획수가 모두 ' + (parities[0] ? '홀수(양)' : '짝수(음)') + '라 배열이 한쪽으로 치우쳐요.' : '홀짝(음양) 획수가 섞여 배열이 안정적이에요.' },
      warns: warns
    };
  }

